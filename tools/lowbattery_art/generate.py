"""Renders the 16 low-battery pictures.

  python3 generate.py preview DIR [N ...]   write PNG previews (all or the listed picture numbers)
  python3 generate.py emit                   write src/images/LowBatteryArt.{h,cpp} (raw-deflate compressed 1-bit data)
"""
import sys
import zlib
from pathlib import Path

import designs_future  # noqa: F401,I001  (each module registers its pictures; the order sets the numbering)
import designs_pop  # noqa: F401,I001
import designs_steam  # noqa: F401,I001
from artlib import H, W, Canvas
from registry import DESIGNS

ROOT = Path(__file__).resolve().parents[2]


def render(i):
    fn = DESIGNS[i - 1][0]
    c = Canvas(seed=i)
    fn(c)
    return c.render()


def pack(im):
    """1 bit per pixel, MSB first, row-major, bit set = ink (black)."""
    raw = im.convert("1").tobytes()
    return bytes((~b) & 0xFF for b in raw)


def deflate_raw(data):
    co = zlib.compressobj(9, zlib.DEFLATED, -15)
    return co.compress(data) + co.flush()


def emit():
    entries = []
    for i in range(1, len(DESIGNS) + 1):
        raw = pack(render(i))
        assert len(raw) == W // 8 * H
        comp = deflate_raw(raw)
        assert zlib.decompressobj(-15).decompress(comp) == raw
        entries.append(comp)
        print(f"{i:02d} {DESIGNS[i - 1][2]:<26} {len(comp):6d} bytes")
    print("total", sum(len(e) for e in entries))
    out = ROOT / "src/images"
    (out / "LowBatteryArt.h").write_text(f"""#pragma once
#include <cstddef>
#include <cstdint>

// Low-battery pictures, generated by tools/lowbattery_art/generate.py.
// Each entry is a raw-deflate stream holding a {W}x{H} 1-bit image (MSB first, bit set = ink).
namespace lowbatteryart {{
constexpr int COUNT = {len(entries)};
constexpr int WIDTH = {W};
constexpr int HEIGHT = {H};
constexpr size_t RAW_BYTES = static_cast<size_t>(WIDTH / 8) * HEIGHT;

struct Entry {{
  const uint8_t* data;
  size_t size;
}};

extern const Entry ENTRIES[COUNT];
}}  // namespace lowbatteryart
""")
    lines = ['#include "LowBatteryArt.h"', "", "// Generated by tools/lowbattery_art/generate.py - do not edit.", ""]
    for i, comp in enumerate(entries, 1):
        lines.append(f"// {i:02d} {DESIGNS[i - 1][1]}")
        lines.append(f"static const uint8_t ART_{i:02d}[] = {{")
        for k in range(0, len(comp), 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in comp[k:k + 16]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("namespace lowbatteryart {")
    lines.append("const Entry ENTRIES[COUNT] = {")
    for i in range(1, len(entries) + 1):
        lines.append(f"    {{ART_{i:02d}, sizeof(ART_{i:02d})}},")
    lines.append("};")
    lines.append("}  // namespace lowbatteryart")
    (out / "LowBatteryArt.cpp").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "preview"
    if mode == "emit":
        emit()
    else:
        outdir = Path(sys.argv[2] if len(sys.argv) > 2 else "preview")
        only = [int(a) for a in sys.argv[3:]]
        outdir.mkdir(parents=True, exist_ok=True)
        for i in (only or range(1, len(DESIGNS) + 1)):
            render(i).convert("L").save(outdir / f"art{i:02d}.png")
